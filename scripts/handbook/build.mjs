import { readFileSync, readdirSync, existsSync, writeFileSync } from 'node:fs'
import { basename, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../../', import.meta.url))
const handbook = join(root, 'handbook')
const images = join(handbook, 'screens')
export const MIN_SCREENSHOTS = 6
export const MIN_SCREENS = 4

export function validateScreens (metadata, imageDir = images) {
  if (!Array.isArray(metadata.screens) || !Array.isArray(metadata.gaps)) throw new Error('Invalid handbook metadata')
  const files = readdirSync(imageDir).filter(name => name.endsWith('.png')).sort()
  if (files.length < MIN_SCREENSHOTS || metadata.screens.length < MIN_SCREENS) throw new Error('Handbook minimum not met')
  const refs = []
  for (const screen of metadata.screens) {
    if (!screen.id || !screen.title || !screen.text || !screen.source || !['changed', 'new', 'flow'].includes(screen.kind)) throw new Error('Invalid screen metadata')
    if (screen.kind !== 'changed' && screen.before !== undefined) throw new Error('Screen has unexpected before image')
    for (const name of screen.kind === 'changed' ? [screen.before, screen.after] : [screen.after]) {
      if (typeof name !== 'string' || basename(name) !== name || !name.endsWith('.png')) throw new Error('Invalid image reference')
      refs.push(name)
    }
  }
  if (new Set(refs).size !== refs.length || refs.length !== files.length || refs.some(name => !files.includes(name))) throw new Error('Image references must match discovered files exactly once')
  for (const name of files) {
    const data = readFileSync(join(imageDir, name))
    if (data.length < 10240 || data.length > 5 * 1024 * 1024 || !data.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10])) || data.toString('ascii', 12, 16) !== 'IHDR' || data.readUInt32BE(16) === 0 || data.readUInt32BE(20) === 0) throw new Error(`Invalid PNG: ${name}`)
  }
  return files
}

export function renderHandbook (metadata) {
  const lines = ['<!-- generated by scripts/handbook/build.mjs; do not edit -->', '# Handbook', '', 'Screens shown by this module in the WDK starter wallet at commit `031e210e8d7ef322a9c3100f5aed3f4b7c6e34e6`.', '']
  const img = (file, title) => `<img src="screens/${file}" alt="${title}" width="280">`
  for (const screen of metadata.screens.filter(item => item.kind === 'changed')) {
    lines.push(`## ${screen.title}`, '', '| Before | After |', '| --- | --- |', `| ${img(screen.before, `${screen.title} before`)} | ${img(screen.after, `${screen.title} after`)} |`, '', screen.text, '')
  }
  for (const screen of metadata.screens.filter(item => item.kind === 'new')) lines.push(`## ${screen.title}`, '', img(screen.after, screen.title), '', screen.text, '')
  lines.push('## Unchanged screens in the sale flow', '')
  for (const screen of metadata.screens.filter(item => item.kind === 'flow')) lines.push(`### ${screen.title}`, '', img(screen.after, screen.title), '', screen.text, '')
  lines.push(`## Not covered (${metadata.gaps.length})`, '')
  for (const gap of metadata.gaps) lines.push(`- **${gap.screen} — ${gap.state}:** ${gap.reason}`)
  lines.push('', '## How the images were made', '')
  for (const screen of metadata.screens) lines.push(`- **${screen.title}:** ${screen.source}`)
  lines.push('', 'Each image passed the [redaction check](redaction.json). The coverage test checks each image against its current redaction record; OCR and QR scanning run separately with `npm run handbook:redaction`.', '')
  return lines.join('\n')
}

export function checkLinks (text, base = handbook) {
  for (const match of text.matchAll(/(?:\]\(|src=")([^)"]+)(?:\)|")/g)) {
    if (!/^(?:https?:|#)/.test(match[1]) && !existsSync(resolve(base, match[1]))) throw new Error(`Missing local link: ${match[1]}`)
  }
}

export function build (check = false) {
  const metadata = JSON.parse(readFileSync(join(handbook, 'screens.json'), 'utf8'))
  validateScreens(metadata)
  const text = renderHandbook(metadata)
  checkLinks(text)
  const target = join(handbook, 'README.md')
  if (check) {
    if (readFileSync(target, 'utf8') !== text) throw new Error('Handbook README differs from generated output')
  } else writeFileSync(target, text)
  return text
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    if (process.argv.length > 3 || (process.argv[2] && process.argv[2] !== '--check')) throw new Error('Usage: build.mjs [--check]')
    build(process.argv[2] === '--check')
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
